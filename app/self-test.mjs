import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createProviderJob, getProviderJob, resolveProviderJob, failProviderJob, claimProviderJobs, releaseProviderJob, reconcileProviderJobs, providerJobStatus } from './provider-job-router.mjs';
import { buildAiGenerationPlan } from './ai-generation-manager.mjs';
import { isPublicHttps } from './url-safety.mjs';

const root=fs.mkdtempSync(path.join(os.tmpdir(),'viral-shorts-test-'));
assert.equal(isPublicHttps('https://example.com/a.mp4'),true);
for(const u of ['http://example.com/a','https://127.0.0.1/a','https://169.254.169.254/a','https://10.0.0.1/a','https://[::1]/a','https://localhost/a'])assert.equal(isPublicHttps(u),false,u);
const job=createProviderJob(root,{provider:'higgsfield',projectId:'p1',sceneIndex:1,kind:'video',verifiedFree:true,prompt:'test',priority:90});
assert.equal(job.status,'pending');assert.equal(job.priority,90);
const leased=claimProviderJobs(root,{provider:'higgsfield',limit:1,workerId:'test-worker',leaseSeconds:30});
assert.equal(leased.length,1);assert.equal(leased[0].status,'leased');assert.equal(leased[0].attempts,1);
const released=releaseProviderJob(root,job.id,'temporary');assert.equal(released.status,'pending');
assert.throws(()=>resolveProviderJob(root,job.id,{url:'http://example.com/a.mp4'}));
assert.throws(()=>resolveProviderJob(root,job.id,{url:'https://127.0.0.1/a.mp4'}));
assert.throws(()=>resolveProviderJob(root,job.id,{url:'https://example.com/a.mp4',kind:'audio'}));
assert.equal(getProviderJob(root,job.id).status,'pending');
const ready=resolveProviderJob(root,job.id,{url:'https://example.com/a.mp4',kind:'video'});assert.equal(ready.status,'ready');
const failed=createProviderJob(root,{provider:'nvidia',projectId:'p1',sceneIndex:2,kind:'image',verifiedFree:true});
failProviderJob(root,failed.id,'no quota');
assert.throws(()=>resolveProviderJob(root,failed.id,{url:'https://example.com/a.jpg'}));
const exp=createProviderJob(root,{provider:'external',projectId:'p2',sceneIndex:1,kind:'image',verifiedFree:true,ttlSeconds:300});
const ef=path.join(root,'provider-jobs',`${exp.id}.json`),er=JSON.parse(fs.readFileSync(ef,'utf8'));er.expiresAt=new Date(Date.now()-1000).toISOString();fs.writeFileSync(ef,JSON.stringify(er));
reconcileProviderJobs(root);assert.equal(getProviderJob(root,exp.id).status,'expired');
const project={storyboard:[{index:1,beat:'hook',durationHint:4},{index:2,beat:'context',durationHint:4},{index:3,beat:'payoff',durationHint:4}],scenes:[{index:1,candidateScore:60},{index:2,candidateScore:90},{index:3,candidateScore:70}]};
const plan=buildAiGenerationPlan(project,{allowance:2,maxScenes:2,minScore:82,provider:'higgsfield'});
assert.deepEqual(plan.selected.map(x=>x.index),[1,3]);
assert.equal(plan.freeOnly,true);assert.equal(plan.paidFallback,false);
const status=providerJobStatus(root);assert.equal(status.counts.ready,1);assert.equal(status.counts.failed,1);assert.equal(status.counts.expired,1);
fs.rmSync(root,{recursive:true,force:true});
console.log('self-test: ok');
